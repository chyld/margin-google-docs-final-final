// Phase 7: the logo goes home; note tags (add, persist, filter, counts, #tag search, remove).
import { chromium } from 'playwright-core'
import { signIn } from './login.mjs'
import { BASE, SHOTS } from './env.mjs'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM ?? '/usr/bin/chromium', headless: true })
let passed = 0, total = 0
const check = (name, ok, detail = '') => { total += 1; if (ok) passed += 1; console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? `  — ${detail}` : ''}`) }
const errors = []
try {
  await signIn(BASE)
  for (const note of await (await fetch(`${BASE}/api/notes`)).json()) await fetch(`${BASE}/api/notes/${note.id}`, { method: 'DELETE' })
  const make = async title => (await (await fetch(`${BASE}/api/notes`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ title }) })).json())
  const older = await make('Older note')
  await new Promise(r => setTimeout(r, 20))
  const newer = await make('Newer note')

  const context = await browser.newContext({ viewport: { width: 1300, height: 860 } })
  await signIn(BASE, context)
  const page = await context.newPage()
  page.on('pageerror', e => errors.push(String(e)))
  page.on('console', m => m.type() === 'error' && !/401/.test(m.text()) && errors.push(m.text()))

  // ---- home ----
  await page.goto(BASE)
  await page.locator('.note-item').first().waitFor()
  await page.waitForTimeout(400)
  check('"/" stays home: no note opens by itself', new URL(page.url()).pathname === '/' && (await page.locator('.document').count()) === 0)
  check('home shows its heading and New note', await page.getByRole('heading', { name: 'Pick a note, or start a new one' }).isVisible() && await page.locator('.home-actions').getByRole('button', { name: 'New note' }).isVisible())

  await page.locator('.note-item', { hasText: 'Older note' }).click()
  await page.locator('.document').waitFor()
  await page.getByRole('link', { name: 'Margin home' }).click()
  await page.waitForURL(u => new URL(u).pathname === '/')
  await page.waitForTimeout(200)
  check('the sidebar logo goes home (no note shown)', (await page.locator('.document').count()) === 0)
  check('focus lands on the home heading', await page.evaluate(() => document.activeElement?.tagName === 'H1'))

  // ---- tags on a note ----
  await page.locator('.note-item', { hasText: 'Older note' }).click()
  await page.locator('.document').waitFor()
  const field = page.getByRole('textbox', { name: 'Add a tag' })
  await field.click()
  await page.keyboard.type('Work, ideas ')
  await page.waitForTimeout(100)
  check('typing "Work, ideas " adds two lowercase chips', JSON.stringify(await page.locator('.tag-chip-name').allTextContents()) === JSON.stringify(['#ideas', '#work']))
  await page.keyboard.type('to-do')
  await page.keyboard.press('Enter')
  check('invalid text stays with a message', (await field.inputValue()) === 'to-do' && (await page.locator('.tag-error').textContent()).includes('a–z and 0–9'))
  await page.keyboard.press('Escape')
  await page.locator('.save-status.is-saved').waitFor({ timeout: 8000 })
  const saved = await (await fetch(`${BASE}/api/notes/${older.id}`)).json()
  check('tags are saved', JSON.stringify(saved.tags) === '["ideas","work"]', JSON.stringify(saved.tags))
  await page.waitForTimeout(600)
  check('the tagged note moved to the top', (await page.locator('.note-item').first().textContent()).includes('Older note'))
  check('its row shows the tags', JSON.stringify(await page.locator('.note-item').first().locator('.note-item-tag').allTextContents()) === '["#ideas","#work"]')
  check('the sidebar lists tags with counts', (await page.locator('.sidebar-tags .tag-pill').count()) === 2)
  await page.reload()
  await page.locator('.tag-chip').first().waitFor()
  check('tags survive a reload', (await page.locator('.tag-chip').count()) === 2)

  // ---- filtering ----
  await fetch(`${BASE}/api/notes/${newer.id}`, { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ tags: ['work'] }) })
  await page.reload()
  await page.locator('.sidebar-tags .tag-pill').first().waitFor()
  const workPill = page.locator('.sidebar-tags .tag-pill', { hasText: '#work' })
  check('counts reflect every note', (await workPill.locator('.tag-pill-count').textContent()) === '2')
  await page.locator('.sidebar-tags .tag-pill', { hasText: '#ideas' }).click()
  await page.waitForTimeout(500)
  check('clicking a tag puts #tag in the search', (await page.getByRole('searchbox', { name: 'Search notes' }).inputValue()) === '#ideas')
  check('…and filters the list', (await page.locator('.note-item').count()) === 1)
  check('…and marks the tag active', (await page.locator('.sidebar-tags .tag-pill.is-active').count()) === 1)
  await page.locator('.sidebar-tags .tag-pill', { hasText: '#ideas' }).click()
  await page.waitForTimeout(500)
  check('clicking it again clears the filter', (await page.locator('.note-item').count()) === 2)
  await page.getByRole('searchbox', { name: 'Search notes' }).fill('#work newer')
  await page.waitForTimeout(600)
  check('#tag plus words narrows by both', (await page.locator('.note-item').count()) === 1 && (await page.locator('.note-item').first().textContent()).includes('Newer'))
  await page.getByRole('searchbox', { name: 'Search notes' }).fill('')
  await page.waitForTimeout(400)

  // ---- removing ----
  await page.locator('.note-item', { hasText: 'Older note' }).click()
  await page.locator('.tag-chip').first().waitFor()
  await page.getByRole('button', { name: 'Remove tag ideas' }).click()
  await page.locator('.save-status.is-saved').waitFor({ timeout: 8000 })
  await page.waitForTimeout(800)
  check('removing a tag saves', JSON.stringify((await (await fetch(`${BASE}/api/notes/${older.id}`)).json()).tags) === '["work"]')
  check('…and the count list follows', (await page.locator('.sidebar-tags .tag-pill').count()) === 1)

  // ---- home tag list, rail logo ----
  await page.getByRole('link', { name: 'Margin home' }).click()
  await page.locator('.home-tags .tag-pill').first().waitFor()
  check('home lists tags with counts', (await page.locator('.home-tags .tag-pill').count()) === 1)
  await page.locator('.sidebar-toggle').click()
  await page.locator('.rail').waitFor()
  await page.locator('.rail-note').first().click()
  await page.locator('.document').waitFor()
  await page.locator('.rail-logo').click()
  await page.waitForURL(u => new URL(u).pathname === '/')
  check('the rail logo goes home', (await page.locator('.document').count()) === 0)
  await page.locator('.home-tags .tag-pill').first().click()
  await page.waitForTimeout(500)
  check('a tag on home expands the collapsed sidebar to show the filtered list', (await page.locator('.rail').count()) === 0 && (await page.locator('.note-item').count()) === 2)
  await context.close()

  // ---- phone ----
  const phone = await browser.newContext({ viewport: { width: 390, height: 800 }, isMobile: true, hasTouch: true })
  await signIn(BASE, phone)
  const p = await phone.newPage()
  await p.goto(BASE)
  await p.getByRole('button', { name: 'Open notes menu' }).click()
  await p.locator('.note-item').first().click()
  await p.locator('.document').waitFor()
  await p.locator('.app-bar-brand').click()
  await p.waitForURL(u => new URL(u).pathname === '/')
  check('phone: the app-bar logo goes home', (await p.locator('.document').count()) === 0)
  await p.getByRole('button', { name: 'Open notes menu' }).click()
  await p.locator('.sidebar.is-open').waitFor()
  await p.locator('.sidebar .brand-link').click()
  await p.waitForTimeout(400)
  check('phone: the drawer logo closes the drawer', !(await p.locator('.sidebar').isVisible()))
  await p.locator('.home-tags .tag-pill').first().click()
  await p.waitForTimeout(500)
  check('phone: a tag on home opens the drawer with the filtered list', (await p.locator('.sidebar.is-open').count()) === 1 && (await p.getByRole('searchbox', { name: 'Search notes' }).inputValue()) === '#work')
  await p.screenshot({ path: `${SHOTS}/p7-phone-filter.png` })
  await phone.close()

  // ---- a typed tag is saved by signing out ----
  const so = await browser.newContext({ viewport: { width: 1300, height: 860 } })
  await signIn(BASE, so)
  const sp = await so.newPage()
  sp.on('dialog', dialog => dialog.accept())
  await sp.goto(BASE)
  await sp.locator('.note-item', { hasText: 'Newer note' }).click()
  await sp.locator('.tag-chip').first().waitFor()
  await sp.getByRole('textbox', { name: 'Add a tag' }).click()
  await sp.keyboard.type('signout1')
  await sp.locator('.user-chip').click()
  await sp.getByRole('button', { name: /Sign out/ }).click()
  await sp.locator('.login-card').waitFor({ timeout: 15000 })
  await signIn(BASE) // that session is gone; check with a fresh one
  check('a typed tag reaches the server when signing out', (await (await fetch(`${BASE}/api/notes/${newer.id}`)).json()).tags.includes('signout1'))
  await so.close()

  check('no console errors', errors.length === 0, errors.slice(0, 3).join(' | '))
} catch (error) {
  check('script ran to completion', false, String(error).split('\n').slice(0, 3).join(' | '))
}
console.log(`${passed}/${total} checks passed`)
await browser.close()
